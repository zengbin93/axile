import assert from 'node:assert/strict'
import { mkdirSync } from 'node:fs'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const base = process.env.PERFORMANCE_PREVIEW_URL ?? 'http://127.0.0.1:1420'
const account = process.env.PERFORMANCE_ACCOUNT_ID ?? '2'
const output = process.env.PERFORMANCE_SCREENSHOTS ?? '/tmp/axon-chart-trades-checks'
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, reducedMotion: 'reduce', colorScheme: 'dark' })
  const errors = [], requests = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (r.url().includes('/costs?')) requests.push(r.url()) })
  await page.goto(`${base}/accounts/${account}/history`)
  const chart = page.getByTestId('performance-chart')
  const markers = page.getByTestId('trade-marker')
  const buys = page.locator('[data-testid=trade-marker][data-side=buy]')
  const card = page.getByTestId('chart-trade-card')
  await markers.first().waitFor()
  assert.equal(await page.getByTestId('execution-strip').count(), 0)
  assert.equal(await page.getByRole('button', { name: '查看成本明细', exact: true }).getAttribute('aria-expanded'), 'false')
  assert.equal(requests.length, 0, 'No cost detail requests until explicitly opened')
  const index = Math.floor(await buys.count() / 2)
  await buys.nth(index).hover()
  await card.waitFor()
  assert.equal(await card.getAttribute('role'), 'tooltip')
  const preview = await card.innerText()
  assert.ok(preview.includes('合计数量与加权均价'))
  assert.ok(preview.includes('BTCUSDT'))
  assert.ok(preview.includes('BP'))
  await page.screenshot({ path: `${output}/hover.png` })
  await buys.nth(index).click()
  assert.equal(await card.getAttribute('role'), 'dialog')
  const pinned = await card.innerText()
  assert.ok(pinned.includes('原持仓'))
  assert.ok(pinned.includes('目标持仓'))
  assert.ok(pinned.includes('执行后'))
  await page.mouse.move(100, 100)
  assert.equal(await card.getAttribute('role'), 'dialog', 'Pinned card survives leaving the chart')
  const viewport = await page.getByTestId('chart-viewport').innerText()
  const link = card.getByRole('link', { name: '执行详情', exact: true })
  const href = await link.getAttribute('href')
  await link.click()
  await page.getByRole('link', { name: '返回实盘绩效' }).click()
  await card.waitFor()
  assert.equal(await card.getByRole('link', { name: '执行详情', exact: true }).getAttribute('href'), href)
  assert.equal(await page.getByTestId('chart-viewport').innerText(), viewport)
  await card.getByRole('button', { name: '全部持仓', exact: true }).click()
  assert.ok((await card.innerText()).includes('执行后持仓'))
  await page.screenshot({ path: `${output}/pinned.png` })
  await card.getByRole('button', { name: '放大成交', exact: true }).click()
  await page.waitForFunction(old => document.querySelector('[data-testid=chart-viewport]').innerText !== old, viewport)
  await page.screenshot({ path: `${output}/zoom.png` })
  await card.getByRole('button', { name: '关闭成交浮层' }).click()
  await page.mouse.move(100, 100)
  await card.waitFor({ state: 'hidden' })
  await chart.dblclick({ position: { x: 100, y: 200 } })
  // Crosshair inspection uses the latest preceding holding snapshot, without a new rail.
  let rect = await chart.boundingBox()
  await page.mouse.move(rect.x + rect.width * 0.4, rect.y + 220)
  await card.waitFor()
  assert.ok((await card.innerText()).includes('执行后持仓'))
  // Existing interval comparison remains available and does not expand the cost table.
  await page.mouse.move(rect.x + rect.width * 0.3, rect.y + 220)
  await page.mouse.down()
  await page.mouse.move(rect.x + rect.width * 0.6, rect.y + 220, { steps: 10 })
  await page.mouse.up()
  await page.getByLabel('比较起点', { exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '查看成本明细', exact: true }).getAttribute('aria-expanded'), 'false')
  await page.getByRole('button', { name: '取消选择', exact: true }).click()
  await buys.nth(3).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await card.scrollIntoViewIfNeeded()
  const bounds = await card.boundingBox()
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390)
  await page.screenshot({ path: `${output}/mobile.png` })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.setViewportSize({ width: 1440, height: 1050 })
  // Isolated response fixtures exercise flat, missing and failed states without modifying account data.
  const response = await page.request.get(`${base}/api/v1/account/performance/${account}/snapshot?range=all`)
  const snapshot = await response.json()
  const source = snapshot.result.executions
  snapshot.result.executions = [source[0], source[Math.floor(source.length / 3)], source[Math.floor(source.length * 2 / 3)]].map((row, i) => ({ ...row, transactions: [], noop: i < 2, positions: i === 0 ? [] : null, positionCount: i === 0 ? 0 : null, reason: i === 2 ? '超过最大下单量，未成交' : '', attempts: i === 2 ? [{ symbol: 'BTCUSDT', planned: 3, filled: 0, reason: '超过最大下单量' }] : [], record: { ...row.record, is_success: i === 2 ? 0 : 1, raw_result: { status: i === 2 ? 'FAILED' : 'NOOP' } } }))
  await page.route('**/api/v1/account/performance/*/snapshot?*', route => route.fulfill({ json: snapshot }))
  await page.reload()
  const warning = page.locator('[data-testid=trade-marker][data-side=warning]')
  await warning.waitFor()
  assert.equal(await markers.count(), 1, 'Flat and normal no-op records do not create markers')
  rect = await chart.boundingBox()
  await page.mouse.move(rect.x + 12 + (rect.width - 90) * 0.2, rect.y + 220)
  await card.waitFor()
  assert.ok((await card.innerText()).includes('空仓'))
  await page.mouse.move(rect.x + 12 + (rect.width - 90) * 0.5, rect.y + 220)
  assert.ok((await card.innerText()).includes('持仓状态未知'))
  await warning.click()
  assert.ok((await card.innerText()).includes('超过最大下单量，未成交'))
  assert.ok((await card.innerText()).includes('计划净交易 3 / 实际净成交 0 BTC'))
  await page.screenshot({ path: `${output}/failure.png` })
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ ok: true, errors, screenshots: output }))
} finally { await browser.close() }
